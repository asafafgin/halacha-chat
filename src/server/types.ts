export type SourceHit = {
  entryId: string
  /** שם הספר בפועל (למשל "ביאור הלכה" בתוך רשומת משנה ברורה) */
  book?: string
  /** מראה מקום בעברית, כפי שהמאגר מחזיר אותו */
  ref: string
  /** לשון המקור, כפי שנמצאה בפועל */
  text: string
  url: string
  /** המאגר שממנו הגיע הטקסט */
  repository: string
  /** דומיין המקור, לסינון אתרים מאושרים */
  domain: string
  /** כשהמחבר יודע אם כל מילות החיפוש נמצאו */
  match?: 'ישיר' | 'סוגיה דומה'
}
